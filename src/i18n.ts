export const dictionaries: Record<Lang, Record<Key, string>> = { zh, en }

export type T = (key: Key, vars?: Record<string, string | number>) => string

export function makeT(lang: Lang): T {
  const dict = dictionaries[lang]
  return (key, vars) => {
    let s = dict[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
}

export function initialLang(): Lang {
  const url = new URLSearchParams(location.search).get('lang')
  if (url === 'zh' || url === 'en') return url
  try {
    const saved = localStorage.getItem('chinese-band-lang')
    if (saved === 'zh' || saved === 'en') return saved
  } catch {
    // Private mode: fall through to the browser language.
  }
  return navigator.languages?.some((l) => l.toLowerCase().startsWith('zh')) ? 'zh' : 'en'
}

export const I18n = createContext<{ lang: Lang; t: T; setLang: (l: Lang) => void }>({
  lang: 'zh',
  t: makeT('zh'),
  setLang: () => {},
})

export const useI18n = () => useContext(I18n)

export function isKey(s: string): s is Key {
  return s in zh
}
